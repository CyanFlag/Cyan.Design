namespace Cyan.Design.Core.Controls.Buttons;

/// <summary>按钮类型</summary>
public enum ButtonType
{
    /// <summary>默认按钮</summary>
    Default,
    /// <summary>主要按钮</summary>
    Primary,
    /// <summary>虚线按钮</summary>
    Dashed,
    /// <summary>文本按钮</summary>
    Text,
    /// <summary>链接按钮</summary>
    Link
}


/// <summary>按钮形状</summary>
public enum ButtonShape
{
    /// <summary>默认形状</summary>
    Default,
    /// <summary>圆形按钮</summary>
    Circle,
    /// <summary>圆角按钮</summary>
    Round
}
